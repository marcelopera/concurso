const { createRequire } = require('node:module');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const runtimeRequire = createRequire('C:/Users/marce/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const { chromium } = runtimeRequire('playwright');

(async () => {
  const evidence = path.resolve(__dirname, '../roadmaps/apofp-2026/evidencias');
  fs.mkdirSync(evidence, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
    // Display the roadmap in this isolated browser even if the user is studying
    // in another window. This changes only this test response, never their session.
    await page.route('**/api/bootstrap', async route => {
      const response = await route.fetch();
      const data = await response.json();
      await route.fulfill({ response, json: { ...data, active_session: null } });
    });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8765');
    await page.getByRole('heading', { name: 'Roadmap · APOFP SP' }).waitFor();
    assert.match(await page.locator('.plan-hero').innerText(), /94[\s\S]*208/);
    assert.match(await page.locator('.daily-plan').innerText(), /4 horas/);
    const current = await (await page.request.get('http://127.0.0.1:8765/api/bootstrap')).json();
    const mappingText = await page.locator('.mapping-overview').innerText();
    for (const value of [current.roadmap.question_mapping.total_occurrences, current.roadmap.question_mapping.linked_occurrences, current.roadmap.question_mapping.current_links]) assert.ok(mappingText.includes(value.toLocaleString('pt-BR')));
    await page.locator('.mapping-overview > details > summary').click();
    assert.equal(await page.locator('.mapping-overview .backlog-link').count(), 4);
    await page.screenshot({ path: path.join(evidence, 'roadmap-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Conteúdo do edital', exact: true }).click();
    await page.getByLabel('Prova', { exact: true }).selectOption('P2');
    assert.equal(await page.locator('.subject-section').count(), 1);
    assert.match(await page.locator('.subject-section').innerText(), /A01.*Orçamento e Finanças Públicas/);
    await page.getByRole('button', { name: /Créditos e alterações/ }).click();
    await page.getByRole('button', { name: 'Configurar', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Conteúdo desta aula no edital' }).waitFor();
    assert.match(await page.locator('.syllabus-card').innerText(), /superávit financeiro/);
    assert.ok(await page.locator('.linked-item').count() > 0);
    await page.locator('.linked-preview > summary').first().click();
    await page.locator('.mapping-evidence > summary').first().click();
    assert.match(await page.locator('.mapping-evidence').first().innerText(), /evidência/);
    await page.screenshot({ path: path.join(evidence, 'aula-com-edital.png'), fullPage: true });
    await page.getByRole('button', { name: 'Abrir roadmap', exact: true }).click();
    await page.getByLabel('Dia do plano', { exact: true }).selectOption('2026-11-22');
    assert.match(await page.locator('.daily-plan').innerText(), /40 questões A01/);
    await page.getByRole('button', { name: 'Conteúdo do edital', exact: true }).click();
    await page.getByLabel('Prova', { exact: true }).selectOption('P1');
    await page.getByPlaceholder('Disciplina, tópico ou aula').fill('Língua Portuguesa');
    await page.getByRole('button', { name: /Texto e semântica/ }).click();
    await page.locator('.lesson-row').filter({ hasText: 'Interpretação, contexto, discursos e figuras de linguagem' }).getByRole('button', { name: 'Configurar', exact: true }).click();
    await page.getByRole('heading', { name: 'Questões vinculadas', exact: true }).waitFor();
    const collection = await (await page.request.get('http://127.0.0.1:8765/api/lessons/apofp26_por_02')).json();
    assert.ok(collection.questions.length > 100);
    assert.ok(collection.questions.every(q => q.contest !== '2025-SEFAZ-RJ-FINANCAS'), 'Financial case references must not enter Portuguese');
    const collectionPages = Math.ceil(collection.questions.length / 15);
    assert.equal(await page.locator('.linked-item').count(), 15);
    assert.ok((await page.locator('.pagination').innerText()).includes('Página 1 de ' + collectionPages));
    await page.locator('.pagination').getByRole('button', { name: 'Próxima', exact: true }).click();
    assert.ok((await page.locator('.pagination').innerText()).includes('Página 2 de ' + collectionPages));
    await page.getByLabel('Somente corrigíveis', { exact: true }).check();
    assert.match(await page.locator('.pagination').innerText(), /Página 1 de/);
    await page.locator('.linked-preview > summary').first().click();
    await page.locator('.mapping-evidence > summary').first().click();
    await page.locator('.linked-filters').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(evidence, 'questoes-vinculadas-desktop.png'), fullPage: false });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Linked collection must fit mobile viewport');
    await page.screenshot({ path: path.join(evidence, 'questoes-vinculadas-mobile.png'), fullPage: false });
    await page.getByRole('button', { name: 'Abrir roadmap', exact: true }).click();
    await page.getByLabel('Dia do plano', { exact: true }).selectOption('2026-10-29');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile page must fit viewport');
    await page.screenshot({ path: path.join(evidence, 'roadmap-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ ok: true, checks: ['desktop roadmap', 'all-base counts', 'coverage gaps', 'P2 filter', 'lesson syllabus', 'mapping evidence', 'large question collection', 'financial-text regression', 'pagination', 'correctable filter', 'simulation calendar', 'mobile layout', 'no browser errors'], evidence }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
